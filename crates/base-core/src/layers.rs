/// The colour of layer i (the last one for a number that is too big).
pub fn color(i: usize) -> [u8; 3] {
    PALETTE[i.min(LAYER_COUNT - 1)]
}

/// Index of the palette colour closest to rgb.
pub fn nearest(rgb: [u8; 3]) -> usize {
    let d = |c: &[u8; 3]| -> i32 { (0..3).map(|i| (c[i] as i32 - rgb[i] as i32).pow(2)).sum() };
    (0..LAYER_COUNT).min_by_key(|&i| d(&PALETTE[i])).unwrap_or(0)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_colours_are_all_different() {
        let set: std::collections::BTreeSet<[u8; 3]> = PALETTE.iter().copied().collect();
        assert_eq!(set.len(), LAYER_COUNT);
        assert_eq!(color(1000), PALETTE[LAYER_COUNT - 1]);
        assert_eq!(nearest(PALETTE[37]), 37);
    }
}
