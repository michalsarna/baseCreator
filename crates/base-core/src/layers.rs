//! The layers every program has: how many, and the colour of each. The same colours in LightCreator, MillCreator and
//! PenCreator. The first 16 are the base colours; the next 16 are lighter versions of them, then pastel ones, then darker
//! ones, so the 64 stay easy to tell apart in rows of 16.

/// How many layers a drawing has.
pub const LAYER_COUNT: usize = 64;

